const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('shop_lang') || 'vi')
  useEffect(() => {
    localStorage.setItem('shop_lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  const t = (key) => (MESSAGES[lang] && MESSAGES[lang][key]) || MESSAGES.vi[key] || key
  return (
    <LangContext.Provider value={{ lang, setLang, toggle: () => setLang(l => l === 'vi' ? 'en' : 'vi'), t }}>
      {children}
    </LangContext.Provider>
  )
}

export const useLang = () => useContext(LangContext)
